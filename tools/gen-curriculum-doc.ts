/**
 * Curriculum doc generator (task M3-01). Writes `docs/curriculum.md`: one Markdown table per biome
 * with each lesson's id, English title, new keys, kind, mode, targets and a sample of what it
 * generates (Miner band, seed 1, the way Mine mode asks for it).
 *
 *   npm run tool -- gen-curriculum-doc            # rewrites docs/curriculum.md
 *   npm run tool -- gen-curriculum-doc --check    # exits 1 when docs/curriculum.md is stale
 *
 * `npm test` checks the file is current (tests/unit/content/curriculum.test.ts), so after editing a
 * lesson, a title or a word list, run this and commit the result. Tables come out already padded
 * the way Oxfmt formats them, so `oxfmt --check` stays clean.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { argv, exit } from "node:process";
import { fileURLToPath } from "node:url";
import type { Lesson } from "../src/content/lessons/types";
import { BIOME_ORDER, type BiomeId } from "../src/types/core";
import {
  curriculumOrder,
  generateFor,
  IN_PROGRESS_BIOMES,
  loadCurriculum,
  messageOf,
  type CurriculumInput,
} from "./validate-curriculum";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DOC_PATH = join(REPO_ROOT, "docs", "curriculum.md");

/** The band and seed of the sample column. */
export const SAMPLE_BAND = "miner";
export const SAMPLE_SEED = 1;
/** Longest sample, in chars, before it is cut at a target boundary. */
export const SAMPLE_MAX = 40;

/** Biome names for this doc (not kid-facing; the game's names live in i18n). */
const BIOME_NAMES: Readonly<Record<BiomeId, string>> = {
  meadow: "Meadow Home",
  birch: "Birch Forest",
  shore: "Sandy Shore",
  frosty: "Frosty Peaks",
  mines: "Deep Mines",
  marsh: "Mushroom Marsh",
  caverns: "Crystal Caverns",
  sparkstone: "Sparkstone Factory",
  citadel: "Sky Citadel",
};

/** A Markdown code span for `text`, with `|` escaped for a table cell. */
function code(text: string): string {
  const fence = text.includes("`") ? "``" : "`";
  const pad = fence.length > 1 || text.startsWith("`") || text.endsWith("`") ? " " : "";
  return `${fence}${pad}${text}${pad}${fence}`.replaceAll("|", String.raw`\|`);
}

/** Plain table text, with `|` escaped. */
const cell = (text: string): string => text.replaceAll("|", String.raw`\|`);

/**
 * The first targets of a run, cut to {@link SAMPLE_MAX} chars at a target boundary. Targets are
 * joined by `sep`: a space, or ` · ` when targets have spaces inside them.
 */
export function sampleText(texts: readonly string[], sep = " "): string {
  let out = "";
  for (const t of texts) {
    const next = out === "" ? t : `${out}${sep}${t}`;
    if (next.length > SAMPLE_MAX && out !== "") return `${out} …`;
    out = next;
  }
  return out;
}

function targetsText(l: Lesson): string {
  const parts = [`accuracy ${Math.round(l.targets.accuracy * 100)}%`];
  if (l.targets.wpmRelative !== undefined) parts.push(`speed ×${l.targets.wpmRelative}`);
  return parts.join(", ");
}

function lengthText(l: Lesson): string {
  const len = l.length;
  if ("chars" in len) return `${len.chars} chars`;
  if ("targets" in len) return `${len.targets} targets`;
  return `${len.seconds} s`;
}

/** A Markdown table with every column padded to its widest cell, as Oxfmt writes it. */
export function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const widths = header.map((h, i) =>
    Math.max(3, h.length, ...rows.map((r) => (r[i] ?? "").length)),
  );
  const line = (cells: readonly string[]): string =>
    `| ${cells.map((c, i) => c.padEnd(widths[i] ?? 0)).join(" | ")} |`;
  return [line(header), line(widths.map((w) => "-".repeat(w))), ...rows.map(line)].join("\n");
}

const spaced = (l: Lesson): boolean => l.kind === "phrases" || l.kind === "sentences";

const HEADER = ["Lesson", "Title", "New keys", "Kind", "Mode", "Length", "Targets", "Sample"];

/** The whole doc. Pure given its input. */
export function renderCurriculumDoc(input: CurriculumInput): string {
  const lessons = curriculumOrder(input.lessons);
  const inProgress = input.inProgress ?? IN_PROGRESS_BIOMES;
  const out: string[] = [
    "# Curriculum",
    "",
    "<!-- Generated by tools/gen-curriculum-doc.ts. Do not edit by hand: run",
    "     `npm run tool -- gen-curriculum-doc`. -->",
    "",
    "Every lesson, biome by biome (PLAN.md §4.2). `tools/validate-curriculum.ts` checks the rules.",
    `The sample is the start of what the lesson generates for the ${SAMPLE_BAND} band with seed`,
    `${SAMPLE_SEED}, before the learner has any key stats. Targets are separated by spaces, or by`,
    "a middle dot (`·`) when they have spaces inside them (phrases and sentences).",
  ];
  for (const biome of BIOME_ORDER) {
    const list = lessons.filter((l) => l.biome === biome);
    if (list.length === 0) continue;
    out.push("", `## ${BIOME_NAMES[biome]} (\`${biome}\`)`, "");
    if (inProgress.has(biome)) out.push("In progress: more lessons are coming.", "");
    const rows = list.map((l) => {
      const run = generateFor(lessons, l, SAMPLE_BAND, SAMPLE_SEED, input.pools);
      const tags = (l.tags ?? []).filter((t) => t !== "intro");
      const kind = tags.length > 0 ? `${l.kind} (${tags.join(", ")})` : l.kind;
      return [
        code(l.id),
        cell(messageOf(input.messages, l.titleKey) ?? "(no title)"),
        l.newKeys.length > 0 ? code(l.newKeys.join(" ")) : "",
        kind,
        l.mode,
        lengthText(l),
        targetsText(l),
        code(
          sampleText(
            run.map((t) => t.text),
            spaced(l) ? " · " : " ",
          ),
        ),
      ];
    });
    out.push(table(HEADER, rows));
  }
  return `${out.join("\n")}\n`;
}

async function main(): Promise<void> {
  const doc = renderCurriculumDoc(await loadCurriculum());
  if (argv.includes("--check")) {
    const current = existsSync(DOC_PATH) ? readFileSync(DOC_PATH, "utf8") : "";
    if (current !== doc) {
      console.error(
        "docs/curriculum.md is stale. Run `npm run tool -- gen-curriculum-doc` and commit it.",
      );
      exit(1);
    }
    console.log("docs/curriculum.md is current");
    return;
  }
  writeFileSync(DOC_PATH, doc);
  console.log("wrote docs/curriculum.md");
}

if (resolve(argv[1] ?? "") === fileURLToPath(import.meta.url)) await main();
