/**
 * Builds `src/content/nickname/filter-data.ts` from the safety blocklist (task M2-11).
 *
 *   npm run tool -- gen-nickname-filter            # rewrite the file
 *   npm run tool -- gen-nickname-filter --check    # exit 1 if the file is out of date
 *
 * The profile screen must check nicknames on the device, but the blocklist never ships as text
 * (M1-10). So this writes only 53-bit hashes of every blocked form: whole words (terms plus their
 * inflections, minus the `allow` section), strict terms (matched inside words), multi-word terms,
 * and multi-word terms with the spaces taken out. `tests/unit/content/nickname.test.ts` fails when the file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { argv, exit } from "node:process";
import { fileURLToPath } from "node:url";
import { hashText } from "../src/content/nickname/hash";
import { inflections, loadBlocklist } from "./validate-wordlists";
import type { Blocklist } from "./validate-wordlists";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const FILTER_FILE = join(REPO_ROOT, "src", "content", "nickname", "filter-data.ts");

const hashed = (s: ReadonlySet<string>): string[] => [...new Set([...s].map(hashText))].toSorted();

/**
 * The hash sets, each sorted so the file is stable. `joined` is every multi-word form with its
 * spaces taken out; only nicknames use it ("bad word" typed as "badword").
 */
export function filterForms(blocklist: Blocklist): {
  words: string[];
  strict: string[];
  phrases: string[];
  joined: string[];
} {
  const words = new Set<string>();
  const strict = new Set<string>();
  const phrases = new Set<string>();
  for (const t of blocklist.terms) {
    const target = t.term.includes(" ") ? phrases : words;
    target.add(t.term);
    for (const form of inflections(t.term)) {
      if (!blocklist.allow.has(form)) target.add(form);
    }
    if (t.strict && !t.term.includes(" ")) strict.add(t.term);
  }
  const joined = new Set([...phrases].map((p) => p.replace(/ /g, "")));
  return {
    words: hashed(words),
    strict: hashed(strict),
    phrases: hashed(phrases),
    joined: hashed(joined),
  };
}

/** Lines of space-separated hashes, each a string literal that fits the formatter's width. */
function packed(name: string, hashes: readonly string[]): string {
  const lines: string[] = [];
  let line = "";
  for (const h of hashes) {
    if (line.length + h.length + 1 > 84) {
      lines.push(line);
      line = "";
    }
    line = line === "" ? h : `${line} ${h}`;
  }
  if (line !== "") lines.push(line);
  return `export const ${name} = [\n${lines.map((l) => `  "${l}",`).join("\n")}\n].join(" ");\n`;
}

export function filterSource(blocklist: Blocklist): string {
  const forms = filterForms(blocklist);
  return [
    "/**",
    " * GENERATED by `npm run tool -- gen-nickname-filter` from",
    " * `src/content/wordlists/blocklist.txt`. Do not edit by hand. Pure.",
    " *",
    " * Hashes (`./hash.ts`) of every blocked form, so the words themselves never ship (M1-10).",
    " */",
    packed("NICKNAME_WORDS", forms.words),
    packed("NICKNAME_STRICT", forms.strict),
    packed("NICKNAME_PHRASES", forms.phrases),
    packed("NICKNAME_JOINED", forms.joined),
  ].join("\n");
}

function main(): void {
  const blocklist = loadBlocklist();
  if (blocklist.problems.length > 0) {
    console.error("The blocklist has problems; run `npm run tool -- validate-wordlists`.");
    exit(1);
  }
  const text = filterSource(blocklist);
  if (argv.includes("--check")) {
    if (readFileSync(FILTER_FILE, "utf8") !== text) {
      console.error(`${FILTER_FILE} is out of date. Run: npm run tool -- gen-nickname-filter`);
      exit(1);
    }
    console.log("nickname filter is up to date");
    return;
  }
  writeFileSync(FILTER_FILE, text);
  console.log(`wrote ${FILTER_FILE}`);
}

if (resolve(argv[1] ?? "") === fileURLToPath(import.meta.url)) main();
